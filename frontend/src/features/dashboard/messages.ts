export type DashMsgKey = keyof typeof MSG;

export function trd(code: DashMsgKey, lang: Lang, params?: Record<string, string | number>): string {
  let str: string = MSG[code][lang];
  if (params) {
    for (const k in params) str = str.replace(`{${k}}`, String(params[k]));
  }
  return str;
}
